-- Ejecutar UNA VEZ en una hoja de Snowflake (Snowsight > Projects > Worksheets)
-- Sustituye TU_USUARIO por tu nombre de usuario de Snowflake.
USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS DBT_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS ANALYTICS;
CREATE ROLE IF NOT EXISTS DBT_ROLE;

GRANT USAGE, OPERATE ON WAREHOUSE DBT_WH TO ROLE DBT_ROLE;
GRANT ALL PRIVILEGES ON DATABASE ANALYTICS TO ROLE DBT_ROLE;
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE_SAMPLE_DATA TO ROLE DBT_ROLE;

GRANT ROLE DBT_ROLE TO USER TU_USUARIO;

-- Comprobación: debe devolver 150000 filas
USE ROLE DBT_ROLE;
